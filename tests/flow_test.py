import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
        pg=await b.new_page(viewport={'width':960,'height':560}); errs=[]
        pg.on('pageerror',lambda e: errs.append('PAGEERROR '+str(e)))
        pg.on('console',lambda m: m.type=='error' and errs.append('CONSOLE '+m.text))
        await pg.goto('http://127.0.0.1:8765/index.html'); await pg.wait_for_timeout(2500)
        await pg.evaluate("window.startFps=()=>{}")
        await pg.click('text=Start mission'); await pg.wait_for_timeout(300); await pg.screenshot(path='h1_howto.png')
        await pg.click("text=LET'S GO"); await pg.wait_for_timeout(500)
        async def skip():
            while await pg.is_visible('#narrNext'): await pg.click('#narrNext')
        await skip()
        await pg.evaluate("()=>{__S().panelDust=0.4}")
        await pg.evaluate("()=>__open('power')"); await pg.wait_for_timeout(300); await pg.screenshot(path='h2_power.png')
        await pg.evaluate("()=>closeOv()")
        await pg.evaluate("()=>__open('rad')"); await pg.wait_for_timeout(300); await pg.screenshot(path='h3_rad.png')
        await pg.evaluate("()=>closeOv()")
        await pg.evaluate("()=>__open('airlock')"); await pg.wait_for_timeout(200); await pg.click('button:has-text("GO OUTSIDE")'); await pg.wait_for_timeout(2500)
        await skip(); await pg.screenshot(path='h3b_out.png')
        print('acts',await pg.evaluate("()=>__S().acts"), 'outside', await pg.evaluate("()=>document.body.classList.contains('outside')"))
        # walk-teleport to crystal
        await pg.evaluate("()=>{const c=__cr().position,cam=__dbg.camera;cam.position.x=c.x+0.5;cam.position.z=c.z+0.5}")
        await pg.wait_for_timeout(1500); await pg.screenshot(path='h4_crystal.png')
        print('samples',await pg.evaluate("()=>__S().samples"))
        if await pg.is_visible('button:has-text("COOL")'): await pg.click('button:has-text("COOL")')
        await skip()
        await pg.evaluate("()=>{const cam=__dbg.camera;cam.position.x=-15;cam.position.z=17}")
        await pg.wait_for_timeout(800)
        print('dust',await pg.evaluate("()=>__S().panelDust"))
        await pg.evaluate("()=>{const cam=__dbg.camera;cam.position.x=0;cam.position.z=-(10)}")
        await pg.wait_for_timeout(500)
        await pg.evaluate("()=>goInside()"); await pg.wait_for_timeout(1800); await skip()
        print('onmars-check acts',await pg.evaluate("()=>__S().acts"))
        await pg.evaluate("()=>__open('bunk')"); await pg.wait_for_timeout(300); await pg.screenshot(path='h45_bunk.png')
        await pg.click('text=END SOL'); await pg.wait_for_timeout(2500)
        await pg.screenshot(path='h5_report.png')
        await skip(); await pg.click('text=NEXT SOL'); await pg.wait_for_timeout(1500); await skip()
        print('sol',await pg.evaluate("()=>__S().sol"))
        await pg.evaluate("()=>endScreen()"); await pg.wait_for_timeout(500); await pg.screenshot(path='h6_end.png')
        print(errs or 'NO ERRORS'); await b.close()
asyncio.run(main())
